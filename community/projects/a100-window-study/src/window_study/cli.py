"""One-command reproduction of every figure and table of this project.

Run from the project directory ``community/projects/a100-window-study/``::

    PYTHONPATH=src python -m window_study.cli

Options: ``--data-dir`` (default: auto-detected repository sample-data dir),
``--channel`` / ``--chirp`` (which real measurement to analyse), ``--seed``.
The default random seed is fixed and no experiment depends on randomness, so
runs are bit-for-bit reproducible.
"""

from __future__ import annotations

import argparse
import logging
import platform
import sys
import time
from pathlib import Path

from . import pipeline, study

logger = logging.getLogger("window_study")

PROJECT_DIR = Path(__file__).resolve().parents[2]


def default_data_dir() -> Path | None:
    """Repository sample-data dir (``ADC数据采集/示例adc数据和结果``), walking up."""
    for base in [PROJECT_DIR, *PROJECT_DIR.parents]:
        cand = base / "ADC数据采集" / "示例adc数据和结果"
        if cand.is_dir():
            return cand
    return None


def _md_table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def write_summary(project_dir: Path, s1: dict, s2: dict, s3: dict, args) -> None:
    lines = [
        "# a100-window-study -- run summary (generated by cli.py)",
        "",
        f"- python {sys.version.split()[0]} on {platform.system()}; "
        f"numpy {__import__('numpy').__version__}",
        f"- data file: `{s2['file']}` (sha256 `{s2['sha256'][:16]}...`)",
        f"- Rx channel {args.channel}, chirp {args.chirp}, seed {args.seed}",
        "",
        "## Experiment 1 -- synthetic window metrics (periodic, N=%d)" % args.nfft,
        "",
        _md_table(
            ["window", "CG", "CG err", "ENBW", "ENBW err", "SLL meas (dB)", "SLL theory (dB)"],
            [
                [
                    name,
                    f"{m['cg']:.6f}",
                    f"{m['cg_abs_err']:.2e}",
                    f"{m['enbw_bins']:.6f}",
                    f"{m['enbw_abs_err']:.2e}",
                    f"{m['sidelobe_db_meas']:.2f}",
                    f"{m['sidelobe_db_theory']:.1f}",
                ]
                for name, m in s1["metrics"].items()
            ],
        ),
        "",
        f"- worst tone-amplitude relative error after CG correction: {s1['worst_amp_rel_err']:.2e}",
        f"- worst Parseval (energy ratio vs sum(w^2)/N) error: {s1['worst_parseval_err']:.2e}; "
        f"FFT Parseval identity error: {s1['worst_fft_parseval_err']:.2e}",
        "",
        "## Experiment 2 -- real far-wave spectra",
        "",
        f"- strongest peak: bin {s2['strong_bin']} ({s2['strong_range_m']:.2f} m)",
        f"- uncompensated coherent-gain offset rect->hann: {s2['cg_offset_rect_to_hann_db']:+.2f} dB",
        f"- clean natural weak-target example found: {s2['clean_natural_found']} "
        "(candidates see results/exp2_natural_candidates.csv)",
        f"- declared two-tone injection (strong @ bin {s2['injection_strong_bin']}, "
        f"weak @ bin {s2['injection_weak_bin']} = {s2['injection_weak_range_m']:.2f} m, "
        f"-{s2['injection_delta_db']:.0f} dB, 4 bins apart): "
        f"hann prominence {s2['injection_hann_prom_db']:+.1f} dB "
        f"(resolved={s2['hann_resolves']}), rect prominence {s2['injection_rect_prom_db']:+.1f} dB "
        f"(resolved={s2['rect_resolves']})",
        "",
        "## Experiment 3 -- normalisation conventions and zero fill",
        "",
        _md_table(
            ["convention", "offset vs C1 (dB)"],
            [[c["convention"], f"{c['offset_vs_c1_db']:+.2f}"] for c in s3["conventions"]],
        ),
        "",
    ]
    zf = s3["zerofill"]
    lines += [
        f"- zero fill: peak delta {zf['peak_delta_db']:+.4f} dB, "
        f"-3 dB width {zf['width3db_a_bins']:.3f} -> {zf['width3db_b_bins']:.3f} bins, "
        f"ENBW {zf['enbw_bins_a']:.4f} -> {zf['enbw_bins_b']:.4f} bins, "
        f"|delta| median {zf['delta_db_median']:.2f} dB / p95 {zf['delta_db_p95']:.2f} dB",
    ]
    (project_dir / "results" / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--data-dir",
        type=Path,
        default=None,
        help="sample data dir (default: <repo>/ADC数据采集/示例adc数据和结果)",
    )
    parser.add_argument("--project-dir", type=Path, default=PROJECT_DIR)
    parser.add_argument("--channel", type=int, default=0, help="Rx channel of the far-wave file")
    parser.add_argument("--chirp", type=int, default=0, help="chirp index to analyse")
    parser.add_argument("--nfft", type=int, default=1024, help="FFT length of the synthetic benchmark")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.INFO if args.verbose else logging.WARNING,
        format="%(levelname)s %(name)s: %(message)s",
    )

    data_dir = args.data_dir if args.data_dir is not None else default_data_dir()
    if data_dir is None:
        print(
            "ERROR: sample data dir not found; pass --data-dir pointing to "
            "'ADC数据采集/示例adc数据和结果' (repository checkout).",
            file=sys.stderr,
        )
        return 2
    data_dir = Path(data_dir)

    t0 = time.perf_counter()
    s1 = study.exp1_synthetic(args.project_dir, nfft=args.nfft, seed=args.seed)
    t1 = time.perf_counter()
    s2 = study.exp2_real(data_dir, args.project_dir, cfg=pipeline.FAR_F0,
                         channel=args.channel, chirp_index=args.chirp)
    t2 = time.perf_counter()
    s3 = study.exp3_normalization(data_dir, args.project_dir, cfg=pipeline.FAR_F0,
                                  channel=args.channel, chirp_index=args.chirp)
    t3 = time.perf_counter()
    write_summary(args.project_dir, s1, s2, s3, args)

    figures = sorted((args.project_dir / "figures").glob("*.png"))
    print(f"exp1 synthetic : {t1 - t0:6.2f} s")
    print(f"exp2 real data : {t2 - t1:6.2f} s")
    print(f"exp3 normalise : {t3 - t2:6.2f} s")
    print(f"figures ({len(figures)}):")
    for f in figures:
        print(f"  {f.name:42s} {f.stat().st_size / 1024:7.1f} KB")
    print("results:")
    for f in sorted((args.project_dir / "results").glob("*")):
        print(f"  {f.name}")
    print(f"total {t3 - t0:.2f} s -- OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
